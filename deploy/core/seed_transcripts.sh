if [ "$MODE" = "--clean" ]; then
  psql_ -c "delete from public.session_transcripts where session_id in (select id from public.sessions where psychologist_id='$PID' and client_id in ($CL))"
  echo "Транскрипты удалены."; exit 0
fi
[ "$(psql_ -c "select count(*) from public.sessions where psychologist_id='$PID' and client_id in ($CL)")" != 0 ] || { echo "Сначала ./seed_test_data.sh $EMAIL" >&2; exit 1; }
[ "$(psql_ -c "select count(*) from public.session_transcripts where session_id in (select id from public.sessions where psychologist_id='$PID' and client_id in ($CL))")" = 0 ] || { echo "Транскрипты уже есть: ./seed_transcripts.sh $EMAIL --clean" >&2; exit 1; }

