select s.id, t.txt, 'manual'
from _t t
join public.clients c on c.name = t.client_name and c.psychologist_id = :'pid'::uuid
join (
  select id, client_id, row_number() over (partition by client_id order by scheduled_at) as rn
  from public.sessions where status = 'completed' and psychologist_id = :'pid'::uuid
