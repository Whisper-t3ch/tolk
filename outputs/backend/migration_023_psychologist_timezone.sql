-- migration_023_psychologist_timezone.sql
--
-- КРИТИЧНЫЙ БАГ, найден прогоном публичной записи: клиент выбирает
-- слот 15:00 — в кабинете психолога сессия появляется на 21:00.
--
-- Причина: вся логика бронирования считает рабочие часы и слоты в UTC
-- (`${date}T${time}:00Z`, getUTCDay, setUTCDate в src/lib/booking.ts),
-- а интерфейс показывает scheduled_at через toLocaleTimeString, то есть
-- в часовом поясе браузера. Психолог, выставляя «работаю с 10:00 до
-- 19:00», имеет в виду своё местное время, а система понимает это как
-- UTC. При тестировании в GMT+6 расхождение составило ровно 6 часов.
--
-- Часовой пояс психолога до сих пор нигде не хранился, поэтому
-- корректно пересчитать время было не из чего.
--
-- Добавляем timezone в профиль психолога (а не в booking_settings):
-- пояс нужен не только для записи, но и для отображения расписания,
-- напоминаний и дат в ассистенте.
--
-- Значение по умолчанию — Europe/Moscow: сервис для русскоязычных
-- психологов, большинство работает по МСК. Формат — IANA-идентификатор
-- ('Europe/Moscow', 'Asia/Yekaterinburg', 'Asia/Vladivostok'), его
-- напрямую понимает Intl API в коде.
--
-- Применять через Supabase SQL Editor. Идемпотентно.
-- ============================================================

alter table psychologists
  add column if not exists timezone text not null default 'Europe/Moscow';

comment on column psychologists.timezone is
  'Часовой пояс психолога в формате IANA (Europe/Moscow, Asia/Yekaterinburg и т.д.). В нём трактуются рабочие часы публичной записи и показывается время сессий. scheduled_at по-прежнему хранится в UTC (timestamptz) — пояс нужен только для преобразования на границах: при создании брони и при отображении.';

