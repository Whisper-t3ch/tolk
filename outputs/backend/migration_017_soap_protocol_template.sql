-- migration_017_soap_protocol_template.sql
--
-- Закрывает обрыв логики: раздел "Шаблоны протоколов" в базе знаний
-- существовал, но никак не применялся к реальной заметке сессии —
-- страница /session/[id]/soap всегда использовала жёстко зашитые
-- 4 поля (S/O/A/P) без какой-либо связи с knowledge_base.
--
-- Решение (лёгкий вариант, без миграции схемы 4 полей): психолог
-- выбирает шаблон протокола из БЗ на странице сессии, текст шаблона
-- используется как подсказка/структура при заполнении/генерации тех
-- же 4 полей. soap_notes.protocol_template_id — просто ссылка на то,
-- какой шаблон использовался при заполнении конкретной заметки
-- (для истории — чтобы потом можно было посмотреть, какой формат
-- использовался).
--
-- Применять через Supabase SQL Editor. Идемпотентно.
-- ============================================================

alter table soap_notes
  add column if not exists protocol_template_id uuid references knowledge_base(id) on delete set null;

comment on column soap_notes.protocol_template_id is
  'Ссылка на knowledge_base.id (source_type=protocol) — какой шаблон протокола психолог выбрал при заполнении этой заметки, для подсказки/структуры полей S/O/A/P. NULL — заполнено без выбора конкретного шаблона (базовый формат по умолчанию).';
