const TEST_TIMEZONE = 'Europe/Moscow';
function buildDateTimeBlock() {
  const now = new Date();
  const weekdayLabel = new Intl.DateTimeFormat('ru', { timeZone: TEST_TIMEZONE, weekday: 'long' }).format(now);
  const dateLabel = new Intl.DateTimeFormat('ru', { timeZone: TEST_TIMEZONE, year: 'numeric', month: 'long', day: 'numeric' }).format(now);
  const timeLabel = new Intl.DateTimeFormat('ru', { timeZone: TEST_TIMEZONE, hour: '2-digit', minute: '2-digit' }).format(now);
  return `Текущая дата и время психолога (часовой пояс ${TEST_TIMEZONE}): ${weekdayLabel}, ${dateLabel}, ${timeLabel} (ISO: ${now.toISOString()}). Используй это как точку отсчёта для "завтра", "через неделю", "в пятницу" и подобных относительных формулировок времени — никогда не угадывай и не бери дату из своих обучающих данных.`;
}

async function callModel(version, messages) {
  const body = {
    modelUri: `gpt://${FOLDER_ID}/${MODEL}`,
    completionOptions: { stream: false, temperature: 0.2, maxTokens: '2000' },
    messages,
    tools: version.tools,
  };
  let res;
  try {
    res = await fetch(URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Api-Key ${API_KEY}`, 'x-folder-id': FOLDER_ID },
      body: JSON.stringify(body),
    });
  } catch (e) {
    return { error: 'fetch failed: ' + String(e) };
  }
  const text = await res.text();
  if (!res.ok) return { error: `HTTP ${res.status}: ${text.slice(0, 500)}` };
  let data;
  try { data = JSON.parse(text); } catch { return { error: 'bad json: ' + text.slice(0, 300) }; }
  const alt = data?.result?.alternatives?.[0] ?? data?.alternatives?.[0];
  const toolCalls = alt?.message?.toolCallList?.toolCalls ?? null;
  const respText = alt?.message?.text ?? null;
  const rawUsage = data?.result?.usage ?? data?.usage;
  const usage = rawUsage
    ? {
        inputTextTokens: Number(rawUsage.inputTextTokens ?? 0),
        completionTokens: Number(rawUsage.completionTokens ?? 0),
        totalTokens: Number(rawUsage.totalTokens ?? 0),
      }
    : null;
  return { toolCalls, text: respText, usage };
}

