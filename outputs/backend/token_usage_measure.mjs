function costRub(totalTokens) { return Math.round((totalTokens / 1000) * price * 10000) / 10000; }

async function runZeroTool(version) {
  const systemPrompt = [version.systemPrompt, buildDateTimeBlock()].join('\n\n');
  // Тема, по которой в реальной базе знаний психолога заведомо пусто —
  // модель должна ответить текстом (suggestWebSearch-ветка), а не найти
  // релевантный контент (мы не подключаем реальный Supabase, но это не
  // важно: сам ВЫЗОВ инструмента и объём system prompt/схемы уже
  // отправлены в LLM независимо от того, что вернул бы инструмент).
  // Здесь специально берём вопрос, где даже без реального RAG-контента
  // модель скорее ответит текстом сама (общий совет, не завязанный на
  // конкретную методику) — это разумная аппроксимация "0 tool calls"
  // сценария из реальных логов (44 из 111 запросов).
  const r = await callModel(version, [
    { role: 'system', text: systemPrompt },
    { role: 'user', text: 'Привет! Напомни, пожалуйста, как в целом лучше начинать первую сессию с новым клиентом — с чего начать разговор?' },
  ]);
  return r;
}

