async function runChained2Call(version) {
  const systemPrompt = [version.systemPrompt, buildDateTimeBlock()].join('\n\n');
  const messages = [
    { role: 'system', text: systemPrompt },
    { role: 'user', text: 'Поставь сессию с Дмитрием на завтра в 10 часов' },
  ];
  const turn1 = await callModel(version, messages);
  if (!turn1.toolCalls) return { turn1, turn2: null, totalTokens: turn1.usage?.totalTokens ?? null, error: turn1.error ?? 'модель не вызвала инструмент на первом шаге' };
  messages.push({ role: 'assistant', toolCallList: { toolCalls: turn1.toolCalls } });
  messages.push({
    role: 'user',
    toolResultList: {
      toolResults: [
        { functionResult: { name: 'find_client_by_name', content: JSON.stringify({ clients: [{ id: '11111111-1111-4111-8111-111111111111', name: 'Дмитрий Волков', status: 'active', request: 'тревога' }] }) } },
      ],
    },
  });
  const turn2 = await callModel(version, messages);
  const totalTokens = (turn1.usage?.totalTokens ?? 0) + (turn2.usage?.totalTokens ?? 0);
  return { turn1, turn2, totalTokens, error: turn2.error ?? null };
}

