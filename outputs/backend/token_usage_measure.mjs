for (const scenarioKey of Object.keys(SCENARIOS)) {
  const baselineAvg = avg(raw[scenarioKey].baseline, 'totalTokens');
  const compressedAvg = avg(raw[scenarioKey].compressed, 'totalTokens');
  const deltaTokens = baselineAvg !== null && compressedAvg !== null ? baselineAvg - compressedAvg : null;
  summary[scenarioKey] = {
    label: SCENARIOS[scenarioKey].label,
    baseline_avg_total_tokens: baselineAvg,
    compressed_avg_total_tokens: compressedAvg,
    delta_tokens: deltaTokens,
    delta_pct: baselineAvg ? (deltaTokens / baselineAvg) * 100 : null,
    baseline_avg_cost_rub: baselineAvg !== null ? costRub(baselineAvg) : null,
    compressed_avg_cost_rub: compressedAvg !== null ? costRub(compressedAvg) : null,
    delta_cost_rub: deltaTokens !== null ? costRub(deltaTokens) : null,
  };
}

