// src/lib/agent/usageLog.ts:estimateCostRub) и переводит разницу в
// токенах в рубли по той же формуле, что и сам продукт:
//   cost_rub = totalTokens / 1000 * PRICE_RUB_PER_1000_TOKENS[model]
// Для yandexgpt-5.1 это 0.8 руб/1000 токенов (см. usageLog.ts).
//
// НЕ импортирует ничего из приложения — та же причина, что и у
