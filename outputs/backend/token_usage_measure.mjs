// (последний аргумент — число повторов на сценарий, по умолчанию 3,
// для усреднения — токены варьируются от прогона к прогону, потому что
// сама модель каждый раз генерирует разный текст/аргументы)
//
// Сценарии (все совпадают по сути вопроса между baseline/compressed —
// иначе сравнение было бы нечестным):
//   1. zero_tool   — вопрос, на который модель отвечает текстом без
//                    вызова инструмента (пустая база знаний по теме) —
//                    изолирует "пол" стоимости: system prompt + схема
//                    18 инструментов + сам вопрос, без RAG-контента.
//   2. one_tool    — один вызов инструмента (find_client_by_name) —
//                    самый частый нетривиальный случай в реальных
//                    логах (31 из 111 запросов, 6.01 руб в среднем).
//   3. chained_2call — двухходовый сценарий (find_client_by_name →
//                    синтетический результат → create_session),
//                    сумма токенов по ОБОИМ вызовам LLM — показывает,
//                    что фиксированная экономия на промпте/схеме
//                    умножается на число итераций в запросе, а не
//                    остаётся разовой.
//
// Вывод: JSON с usage по каждому сценарию/версии/повтору + сводка
// (среднее по сценарию, дельта в токенах и рублях, дельта в % от
// среднего числа итераций реальных логов) в конце.
// ============================================================
import { readFileSync } from 'node:fs';

const envPath = process.argv[2] || './.env.local';
const envRaw = readFileSync(envPath, 'utf8');
const env = {};
for (const line of envRaw.split('\n')) {
  const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
}

const API_KEY = env.YANDEX_GPT_API_KEY;
const FOLDER_ID = env.YANDEX_GPT_FOLDER_ID;
if (!API_KEY || !FOLDER_ID) { console.error('Missing YANDEX_GPT_API_KEY/YANDEX_GPT_FOLDER_ID in ' + envPath); process.exit(1); }

const MODEL = process.argv[3] || 'yandexgpt-5.1';
const REPS = Number(process.argv[4] || 3);
const URL = 'https://llm.api.cloud.yandex.net/foundationModels/v1/completion';

const PRICE_RUB_PER_1000_TOKENS = {
  'yandexgpt/latest': 1.2,
  'yandexgpt-5.1': 0.8,
  'yandexgpt-lite/latest': 0.2,
};
const price = PRICE_RUB_PER_1000_TOKENS[MODEL];
if (price === undefined) {
  console.error(`Нет цены для модели "${MODEL}" в PRICE_RUB_PER_1000_TOKENS — добавь вручную, либо используй yandexgpt-5.1 / yandexgpt/latest / yandexgpt-lite/latest.`);
  process.exit(1);
}

