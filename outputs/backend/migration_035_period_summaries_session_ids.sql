-- ============================================================
-- migration_035_period_summaries_session_ids.sql
--
-- Готовит почву для кэша get_period_summary (Уровень 1.3 из списка
-- оптимизаций стоимости, 20.09) — психолог, дважды подряд просящий
-- срез по одному клиенту за тот же период, не должен платить дважды.
--
-- Кэш-хит должен сверяться по ТОЧНОМУ набору session_ids, а не по
-- period_start/period_end/sessions_count — иначе новая сессия внутри
-- того же диапазона дат (или отменённая/удалённая сессия, меняющая
-- sessions_count при том же числе дат) даст ложный кэш-хит с
-- устаревшим содержанием. period_summaries сейчас не хранит, какие
-- именно сессии вошли в срез — только агрегаты. Эта миграция
-- добавляет недостающую колонку.
--
-- Аддитивное изменение, идемпотентно, не трогает существующие записи
-- (session_ids остаётся NULL для них — код кэша должен трактовать
-- NULL как "нет данных для сверки", то есть промах кэша, не ошибку).
-- ============================================================

alter table period_summaries
  add column if not exists session_ids uuid[];

comment on column period_summaries.session_ids is
  'Точный набор sessions.id, вошедших в этот срез — для проверки кэш-хита по точному совпадению множества (не по датам/количеству). NULL у записей, созданных до этой миграции.';

create index if not exists idx_period_summaries_client_session_ids
  on period_summaries using gin (session_ids);
