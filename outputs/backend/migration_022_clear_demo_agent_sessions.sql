-- Найдено сквозным прогоном: в чате ассистента лежит сохранённая
-- переписка с конкретными клиническими цифрами по клиентам —
-- «По GAD-7 у Марии устойчивое снижение: 17 → 14 → 12 → 10 баллов за
-- четыре замера», «у Игоря Смирнова низкое выполнение домашних заданий
-- (2 из 6) и PHQ-9 ... (16/27)», «домашнее задание отправлено Дмитрию
-- в Telegram».
--
-- Ни одного из этих фактов в базе нет: test_results на момент проверки
-- была пуста, homework — пуста, интеграция с Telegram не подключена.
-- То есть психолог видит в интерфейсе выдуманные баллы по реальным
-- именам своих клиентов и может принять их за настоящие. Для
-- психодиагностики это прямой риск: на такие цифры опираются при
-- решениях о ходе терапии.
--
-- Эта миграция чистит историю чатов с ассистентом. Реальные данные
-- (клиенты, сессии, протоколы, результаты тестов) не затрагиваются —
-- agent_sessions хранит только переписку с ассистентом, она
-- восстановлению не подлежит и не нужна.
--
-- Применять через Supabase SQL Editor.
-- ============================================================

