-- migration_016_remove_unverified_tests.sql
--
-- Удаляет из knowledge_base 5 тестов, для которых НЕ удалось найти
-- точный официальный бланк вопросов + ключ подсчёта (после двух
-- раундов исследования, см. migration_012/014). Выдуманные вопросы
-- или неточный ключ подсчёта в психодиагностике недопустимы —
-- решено убрать эти материалы из БЗ полностью, а не оставлять как
-- текстовые "заглушки" без интерактивной формы:
--
--   - Опросник уровня субъективного контроля (УСК, Бажин-Голынкина-Эткинд)
--   - СМИЛ (Стандартизированный многофакторный метод исследования личности)
--   - Опросник родительского отношения (ОРО, А.Я. Варга, В.В. Столин)
--   - Опросник перфекционизма (Н.Г. Гаранян, А.Б. Холмогорова, Т.Ю. Юдеева)
--   - Шкала академической прокрастинации (адаптация Я.И. Варваричевой)
--
-- Соответствующие записи также удалены из src/lib/approaches.ts —
-- новые психологи их больше не получат при онбординге/ресиде.
--
-- Применять через Supabase SQL Editor. Идемпотентно — безопасно
-- применять повторно (DELETE на несуществующих строках не ошибётся).
-- ============================================================

delete from knowledge_base
where source_type = 'test'
  and title in (
    'Опросник уровня субъективного контроля (УСК, Бажин-Голынкина-Эткинд)',
    'СМИЛ (Стандартизированный многофакторный метод исследования личности) — назначение',
    'Опросник родительского отношения (ОРО, А.Я. Варга, В.В. Столин)',
    'Опросник перфекционизма (Н.Г. Гаранян, А.Б. Холмогорова, Т.Ю. Юдеева)',
    'Шкала академической прокрастинации (адаптация Я.И. Варваричевой)'
  );
