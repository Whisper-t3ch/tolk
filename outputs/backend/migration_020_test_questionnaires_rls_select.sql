-- БЛОКЕР БЕТЫ, найден сквозным прогоном интерфейса.
--
-- Симптом: в разделе «База знаний → Тесты» карточка методики помечена
-- бейджем «Интерактивный опросник», но при попытке «Отправить как тест
-- клиенту» приходит ответ «Этот тест ещё не переведён в формат
-- интерактивного опросника» — и так для всех 22 методик, то есть
-- назначить клиенту нельзя вообще ничего.
--
-- Причина: на test_questionnaires включена RLS, но нет ни одной
-- политики SELECT. Postgres в таком случае возвращает пустой набор
-- молча, без ошибки — поэтому и в API, и в диагностике всё выглядело
-- как «таблица пустая». Проверка service-role клиентом показала, что
-- все 22 опросника на месте:
--   сессия психолога -> 0 строк
--   service role     -> 22 строки
--
-- Публичные маршруты (/api/public/test/*) работали, потому что ходят
-- через createAdminClient() и обходят RLS. Ломался только серверный
-- маршрут /api/clients/[id]/tests/send, который (правильно) ходит от
-- имени психолога.
--
-- Решение: разрешить чтение справочника любому залогиненному
-- психологу. Персональных данных таблица не содержит — это общий
-- каталог методик, не привязанный к psychologist_id (так и задумано
-- в migration_011). Запись остаётся только у service role.
--
-- Применять через Supabase SQL Editor. Идемпотентно.
-- ============================================================

alter table test_questionnaires enable row level security;

drop policy if exists "test_questionnaires_select_authenticated" on test_questionnaires;

create policy "test_questionnaires_select_authenticated"
  on test_questionnaires
  for select
  to authenticated
  using (true);

