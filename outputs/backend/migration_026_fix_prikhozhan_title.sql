--
-- Найдено при прогоне: карточка методики в базе знаний называлась
-- «Шкала тревожности Спилбергера для детей и подростков (адаптация
-- А.М. Прихожан)» — фактически неверно. Методика А.М. Прихожан
-- («Шкала личностной тревожности для учащихся») — самостоятельный
-- инструмент со своей структурой (4 субшкалы: школьная, самооценочная,
-- межличностная, магическая тревожность), а не адаптация теста
-- Спилбергера (у которого две шкалы — ситуативная и личностная
-- тревожность; в базе знаний он отдельно описан как «Спилбергера-
-- Ханина»). Название и содержимое карточки противоречили друг другу.
--
-- Психолог видел одно название в базе знаний, а при открытии
-- интерактивной формы (test_questionnaires.title, независимый
-- источник) — другое, «Шкала личностной тревожности для учащихся
-- (А.М. Прихожан)». Эта миграция приводит title в knowledge_base к
-- тому же виду.
--
-- Применять через Supabase SQL Editor. Идемпотентно.
-- ============================================================

update knowledge_base
set title = 'Шкала личностной тревожности для учащихся (А.М. Прихожан)'
where questionnaire_key = 'PRIKHOZHAN'
  and title = 'Шкала тревожности Спилбергера для детей и подростков (адаптация А.М. Прихожан)';

