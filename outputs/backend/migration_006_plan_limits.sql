-- ============================================================
-- ТОЛК — миграция 006: тариф психолога (plan_name) и лимиты
-- ============================================================
-- Контекст: лимит запросов к ассистенту уже проверяется/списывается
-- в src/lib/assistantLimits.ts через колонки assistant_requests_used /
-- assistant_requests_limit / assistant_requests_reset_at (созданы
-- более ранней миграцией, файл которой не сохранён в репозитории).
--
-- До этой миграции лимит хранился как голое число в
-- assistant_requests_limit без привязки к тарифу — значит смена
-- условий тарифа требовала вручную обновлять лимит у каждого
-- психолога в БД. Теперь лимит вычисляется в коде из PLAN_LIMITS по
-- plan_name (см. src/lib/assistantLimits.ts) — смена условий тарифа
-- это правка одной константы, а не миграция данных.
--
-- Все участники беты получают plan_name='beta' автоматически через
-- DEFAULT — при регистрации им не нужно ничего присваивать вручную.
-- Переход на платный тариф после беты — ручное обновление plan_name
-- (через админку, когда она появится, либо напрямую в Supabase).

alter table psychologists
  add column if not exists plan_name text not null default 'beta'
  check (plan_name in ('beta', 'practice', 'professional', 'expert'));

comment on column psychologists.plan_name is
  'Тариф психолога. Определяет лимит запросов к ассистенту (см. PLAN_LIMITS в src/lib/assistantLimits.ts) и в будущем — доступность фич по тарифу (Vision, контент, режим Супервизор и т.д.)';

-- assistant_requests_limit больше не является источником истины для
-- лимита (см. resetIfDue в assistantLimits.ts, теперь берёт лимит из
-- PLAN_LIMITS[plan_name]) — колонку не удаляем, чтобы не ломать
-- существующие данные и на случай отладки/ручного оверрайда лимита
-- конкретному психологу в будущем, но новый код её больше не читает.
