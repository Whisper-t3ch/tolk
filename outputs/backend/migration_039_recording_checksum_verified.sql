--
-- ПОРЯДОК ПРИМЕНЕНИЯ: строго после migration_038_recording_attempt_id
-- (часть 1). Само по себе добавление checksum_verified не зависит от
-- attempt_id технически (это независимый столбец), но следует после
-- неё по описанной выше причине — не копить несогласованные миграции.
--
-- Контекст: раньше сервер сам пересчитывал sha256 от реальных байт
-- фрагмента при приёме (байты проходили через Vercel). После перехода
-- на прямую загрузку в Storage (браузер → Storage, минуя Vercel)
-- сервер байт не видит вообще — checksum в session_recording_chunks
-- теперь ЗАЯВЛЕННОЕ браузером значение, не подтверждённое сервером.
-- Этот столбец делает это состояние явным и проверяемым, а не только
-- задокументированным в комментариях кода.
--
-- ТОЧНАЯ СЕМАНТИКА (уточнено 24.09 по прямому требованию, п.4):
--   false = "байты ЕЩЁ НЕ СВЕРЕНЫ" — нормальное, ожидаемое состояние
--     сразу после direct-upload. НЕ означает "проверка не удалась" и
--     НЕ означает "с чанком что-то не так" — это дефолт для каждой
--     новой строки, пока не наступит этап ниже.
--   true = сервис (Этап 3, сборка дорожки перед GigaAM — ЕЩЁ НЕ
--     РЕАЛИЗОВАН на 24.09) СКАЧАЛ объект из Storage, посчитал его
--     РЕАЛЬНЫЙ SHA-256 и сравнил с ожидаемым значением, они СОВПАЛИ.
--     Выставляется РОВНО в этот момент, не раньше.
--   Несовпадение при этой сверке — это НЕ "выставить false и продолжить
--     (оно и так false по умолчанию), это должно ОСТАНАВЛИВАТЬ
--     обработку дорожки (не запускать GigaAM на этом чанке/дорожке),
--     а не только писать предупреждение в лог. Это требование к
--     БУДУЩЕМУ коду Этапа 3, здесь фиксируется как обязательная
--     семантика заранее, раз столбец создаётся сейчас, а не тогда.
--
-- НЕ ПРИМЕНЕНО К ПРОД-БД — подготовлено, ждёт вашего разрешения (тот
-- же протокол, что и для migration_038 и предыдущих миграций этого
-- проекта). Таблица session_recording_chunks пустая на момент
-- подготовки (0 строк, проверено 24.09 напрямую через
-- mcp__Supabase__execute_sql) — риск для существующих данных нулевой.

alter table public.session_recording_chunks
  add column if not exists checksum_verified boolean not null default false;

comment on column public.session_recording_chunks.checksum_verified is
  'false = checksum заявлен браузером, сервер его ещё не проверял (нормальное состояние сразу после direct-upload, НЕ признак ошибки). true выставляется ТОЛЬКО на этапе сборки дорожки перед GigaAM (Этап 3, ещё не реализован), и только после реального скачивания байт из Storage и совпадения их SHA-256 с ожидаемым значением. Несовпадение на этом этапе обязано блокировать обработку дорожки, не просто логировать предупреждение — см. заголовок migration_039.';
