-- migration_038_recording_checksum_verified.sql
--
-- Добавлено 24.09.2026 по итогам ревью границ доверия signed-upload
-- пайплайна (ветка recording-signed-upload-24-09, ещё не в main).
--
-- Контекст: раньше сервер сам пересчитывал sha256 от реальных байт
-- фрагмента при приёме (байты проходили через Vercel). После перехода
-- на прямую загрузку в Storage (браузер → Storage, минуя Vercel)
-- сервер байт не видит вообще — checksum в session_recording_chunks
-- теперь ЗАЯВЛЕННОЕ браузером значение, не подтверждённое сервером.
-- Этот столбец делает это состояние явным и проверяемым, а не только
-- задокументированным в комментариях кода — по прямому запросу
-- пользователя: "пометь checksum как unverified... не отображай такой
-- chunk как криптографически проверенный".
--
-- НЕ ПРИМЕНЕНО К ПРОД-БД — подготовлено, ждёт вашего разрешения (тот
-- же протокол, что и для предыдущих миграций в этом проекте). Таблица
-- session_recording_chunks сейчас пустая (0 строк, живой тест ещё не
-- проведён) — риск для существующих данных нулевой в любом случае.
--
-- Кто должен выставлять true: этап сборки дорожки перед GigaAM
-- (Этап 3, ещё не реализован) — единственное место, где байты и так
-- скачиваются целиком и checksum можно реально пересчитать и сверить.
-- Ничто до этого момента не должно читать checksum_verified как true.

alter table public.session_recording_chunks
  add column if not exists checksum_verified boolean not null default false;

comment on column public.session_recording_chunks.checksum_verified is
  'false = checksum заявлен браузером, сервер его не проверял (нормальное состояние после direct-upload, см. migration_038). true выставляется только на этапе сборки дорожки перед GigaAM (Этап 3), после реального чтения и хеширования байт из Storage.';
