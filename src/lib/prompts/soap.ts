// ============================================================
// Промпты для генерации SOAP-протокола через YandexGPT Pro.
//
// Два варианта, соответствующие session_transcripts.source в схеме БД:
// - SOAP_SYSTEM_PROMPT_JITSI_GIGAAM — основной путь. На входе полный
//   транскрипт сессии (спикер-сегментированный, с артефактами
//   распознавания речи) + заметки психолога + краткое резюме
//   предыдущих сессий.
// - SOAP_SYSTEM_PROMPT_MANUAL_DEGRADE — запасной путь при сбое
//   воркера GigaAM посреди сессии. На входе только заметки психолога
//   (TipTap) + резюме предыдущих сессий, транскрипта нет.
//
// Оба промпта требуют строгий JSON-ответ { s, o, a, p } —
// соответствует полям s_subjective/o_objective/a_assessment/p_plan
// в таблице soap_notes.
// ============================================================

export interface SoapGenerationInput {
  /** Полный текст транскрипта с речевыми артефактами. Отсутствует в деградированном режиме. */
  transcript?: string;
  /** Ручные заметки психолога (TipTap → plain text или markdown). */
  notes: string;
  /** Краткое резюме предыдущих сессий с этим клиентом (2-4 предложения на сессию, самые свежие последними). */
  previousSessionsSummary?: string;
  clientName: string;
  sessionNumber: number;
}

export interface SoapResult {
  s: string;
  o: string;
  a: string;
  p: string;
}

const JSON_CONTRACT = `Отвечай СТРОГО в формате JSON без markdown-обрамления (без \`\`\`json), без комментариев до или после:
{"s": "...", "o": "...", "a": "...", "p": "..."}

Требования к содержимому:
- Каждое поле — связный текст на русском языке (не список тезисов), 3-6 предложений.
- Конкретика вместо общих фраз: цифры, даты, прямые формулировки клиента в кавычках, названия техник и заданий.
- Не выдумывай данные, которых нет во входных материалах (числовые баллы тестов, диагнозы, факты) — если данных недостаточно для какого-то поля, честно отметь это одной фразой внутри поля, но само поле не оставляй пустым.
- Блок "p" обязательно содержит: (1) конкретное домашнее задание для клиента, (2) план фокуса следующей сессии.`;

export const SOAP_SYSTEM_PROMPT_JITSI_GIGAAM = `Ты — ассистент психолога, помогающий вести клиническую документацию в формате SOAP (Subjective / Objective / Assessment / Plan) по стандартам психологического консультирования.

На входе — транскрипт сессии, автоматически распознанный из аудио (спикеры размечены как ПСИХОЛОГ и КЛИЕНТ), ручные заметки психолога и краткое резюме предыдущих сессий с этим клиентом.

ВАЖНО про транскрипт: это автоматическая расшифровка речи, в ней есть артефакты распознавания — оборванные слова ("тре вога", "хоте... то есть"), слова-паразиты ("ну вот", "это самое", "э-э", "как бы"), самоисправления клиента на лету, и пометки [неразборчиво] в местах, где распознавание не справилось. Твоя задача — понимать смысл сказанного СКВОЗЬ эти артефакты, никогда не копировать их в итоговый протокол и не упоминать сам факт "плохого качества записи" — работай так, как будто читаешь чистую стенограмму.

Собери информацию по блокам:
- S (Субъективно): что сообщает клиент о своём состоянии, переживаниях, событиях недели — его словами (можно короткими цитатами в кавычках, уже без артефактов распознавания), включая как он сам оценивает динамику.
- O (Объективно): наблюдаемые психологом факты — выполнение домашнего задания (что именно и в каком объёме), измеримые показатели, если они прозвучали в сессии (баллы шкал, тестов), поведенческие наблюдения психолога о клиенте на самой сессии, если психолог их проговаривает.
- A (Оценка): клиническая интерпретация психолога — паттерны, которые видны в материале (в том числе повторяющиеся из предыдущих сессий, если это видно по резюме), динамика по сравнению с прошлым, гипотезы, к которым склоняется терапевтическая работа.
- P (План): конкретные следующие шаги — домашнее задание клиенту (что именно), фокус следующей сессии, любые техники, которые психолог назвал использовать дальше.

Используй резюме предыдущих сессий только для контекста преемственности (например: "тревога снизилась с 7-8 до 6 баллов по сравнению с прошлой сессией") — не пересказывай его как будто это происходило сейчас.

${JSON_CONTRACT}`;

export const SOAP_SYSTEM_PROMPT_MANUAL_DEGRADE = `Ты — ассистент психолога, помогающий вести клиническую документацию в формате SOAP (Subjective / Objective / Assessment / Plan).

ВНИМАНИЕ: это деградированный режим. Аудиозапись сессии не была получена (сбой сервиса транскрибации), поэтому у тебя есть только ручные заметки психолога (обычно короткие, тезисные, сделанные прямо во время или сразу после сессии) и краткое резюме предыдущих сессий с этим клиентом. Полного транскрипта разговора нет.

Твоя задача — по этим неполным данным восстановить максимально осмысленный SOAP-протокол, но честно обозначить неполноту там, где заметок недостаточно, а не додумывать детали, которых психолог не записал.

Правила:
- В самом начале поля "s" (Субъективно) обязательно добавь пометку: "[Данные могут быть неполными — запись прервалась]" — и дальше уже содержательный текст на основе заметок.
- Не изобретай прямые цитаты клиента, если их нет в заметках дословно — только пересказывай то, что psychlog реально зафиксировал.
- Если заметок недостаточно для содержательного блока O (Объективно) — так и напиши: что психолог не зафиксировал измеримых наблюдений в этот раз, но не оставляй поле пустым.
- Блок A (Оценка) и P (План) строй на основе того, что есть в заметках плюс контекст предыдущих сессий (преемственность динамики).

${JSON_CONTRACT}`;

export function buildSoapUserMessage(input: SoapGenerationInput): string {
  const parts: string[] = [];

  parts.push(`Клиент: ${input.clientName}`);
  parts.push(`Сессия №${input.sessionNumber}`);

  if (input.previousSessionsSummary) {
    parts.push(`\n--- Резюме предыдущих сессий ---\n${input.previousSessionsSummary}`);
  }

  if (input.transcript) {
    parts.push(`\n--- Транскрипт текущей сессии ---\n${input.transcript}`);
  }

  parts.push(`\n--- Заметки психолога ---\n${input.notes || "(заметок нет)"}`);

  return parts.join("\n");
}

export function selectSoapSystemPrompt(hasTranscript: boolean): string {
  return hasTranscript ? SOAP_SYSTEM_PROMPT_JITSI_GIGAAM : SOAP_SYSTEM_PROMPT_MANUAL_DEGRADE;
}
