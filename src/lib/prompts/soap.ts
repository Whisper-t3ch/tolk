// ============================================================
// Промпты для генерации протокола сессии через YandexGPT Pro.
//
// Формат — русскоязычный, основан на реальной практике ведения
// заметок консультирующими психологами (а не на медицинском SOAP):
// жалоба и запрос клиента его словами → контекст и наблюдения →
// гипотеза психолога → договорённости и план. Поля в БД (s/o/a/p —
// историческое наследие названий колонок soap_notes.s_subjective и
// т.д.) переиспользуются как есть, смысл полей поменялся на русский,
// сама структура таблицы не менялась.
//
// Два варианта, соответствующие session_transcripts.source в схеме БД:
// - PROTOCOL_SYSTEM_PROMPT_JITSI_GIGAAM — основной путь. На входе полный
//   транскрипт сессии (спикер-сегментированный, с артефактами
//   распознавания речи) + заметки психолога + краткое резюме
//   предыдущих сессий.
// - PROTOCOL_SYSTEM_PROMPT_MANUAL_DEGRADE — запасной путь при сбое
//   воркера GigaAM посреди сессии. На входе только заметки психолога
//   (TipTap) + резюме предыдущих сессий, транскрипта нет.
//
// Оба промпта требуют строгий JSON-ответ { s, o, a, p } —
// соответствует полям s_subjective/o_objective/a_assessment/p_plan
// в таблице soap_notes.
// ============================================================

export interface SoapGenerationInput {
  /** Полный текст транскрипта с речевыми артефактами. Отсутствует в деградированном режиме. */
  transcript?: string;
  /** Ручные заметки психолога (TipTap → plain text или markdown). */
  notes: string;
  /** Краткое резюме предыдущих сессий с этим клиентом (2-4 предложения на сессию, самые свежие последними). */
  previousSessionsSummary?: string;
  clientName: string;
  sessionNumber: number;
  /**
   * Текст выбранного психологом шаблона протокола из базы знаний
   * (knowledge_base, source_type=protocol) — если указан, модель должна
   * ориентироваться на структуру/акценты именно этого шаблона при
   * распределении информации по блокам s/o/a/p (схема БД не меняется,
   * это только влияет на СОДЕРЖАНИЕ каждого поля).
   */
  templateContent?: string;
  templateTitle?: string;
}

export interface SoapResult {
  s: string;
  o: string;
  a: string;
  p: string;
}

/**
 * Правила «только из материалов» — общие для обоих промптов. Дублируются
 * детерминированной пост-проверкой (lib/soap/groundedness.ts), но модель
 * должна следовать им сама.
 */
const GROUNDING_RULES = `ЖЁСТКИЕ ПРАВИЛА (нарушение недопустимо — результат это AI-черновик, который проверяет психолог):
- Используй ТОЛЬКО информацию из переданных материалов. Ничего не добавляй от себя.
- НЕ добавляй диагнозы, названия расстройств и синдромов, клинические интерпретации и гипотезы, если психолог не произносил их сам.
- НЕ придумывай упражнения, домашние задания, техники и рекомендации. Включай их, только если психолог явно их назвал.
- НЕ придумывай цитаты, числа, баллы шкал, даты и факты. Цитата допустима только дословно из транскрипта.
- НЕ делай выводов из того, чего не было: молчание, обрывки фраз и шум распознавания не являются жалобой, симптомом или темой.
- Слово-маркер "[нецензурное слово]" означает, что клиент выразился резко; не восстанавливай слово, можно отметить эмоциональную остроту.
- Если для раздела недостаточно оснований, запиши в нём ровно: "Недостаточно данных" (можно добавить одну фразу, чего именно не хватает). Не заполняй раздел «для объёма».`;

const JSON_CONTRACT = `${GROUNDING_RULES}

Отвечай СТРОГО в формате JSON без markdown-обрамления (без \`\`\`json), без комментариев до или после:
{"s": "...", "o": "...", "a": "...", "p": "..."}

Требования к содержимому:
- Каждое поле — связный текст на русском языке, не более 6 предложений; если данных мало — короче или "Недостаточно данных".
- Конкретика вместо общих фраз: только то, что есть в материалах.
- Поле не оставляй пустой строкой: либо содержательный текст по материалам, либо "Недостаточно данных".`;

export const PROTOCOL_SYSTEM_PROMPT_JITSI_GIGAAM = `Ты — ассистент психолога, помогающий вести записи консультаций в формате, принятом у практикующих психологов в России: жалоба и запрос клиента, контекст и наблюдения, гипотеза психолога, договорённости и план.

На входе — транскрипт сессии, автоматически распознанный из аудио (спикеры размечены как ПСИХОЛОГ и КЛИЕНТ), ручные заметки психолога и краткое резюме предыдущих сессий с этим клиентом.

ВАЖНО про транскрипт: это автоматическая расшифровка речи, в ней есть артефакты распознавания — оборванные слова ("тре вога", "хоте... то есть"), слова-паразиты ("ну вот", "это самое", "э-э", "как бы"), самоисправления клиента на лету, и пометки [неразборчиво] в местах, где распознавание не справилось. Твоя задача — понимать смысл сказанного СКВОЗЬ эти артефакты, никогда не копировать их в итоговый протокол и не упоминать сам факт "плохого качества записи" — работай так, как будто читаешь чистую стенограмму.

Собери информацию по блокам:
- s (Жалоба и запрос клиента): что сообщает клиент о своём состоянии, переживаниях, событиях недели — его словами (можно короткими цитатами в кавычках, уже без артефактов распознавания), включая как он сам оценивает динамику.
- o (Контекст и наблюдения): только факты, которые прозвучали или записаны: выполнение домашнего задания (если о нём говорили), показатели, названные в сессии (баллы шкал, тестов), наблюдения психолога о клиенте, если он их проговаривает. Иначе — "Недостаточно данных".
- a (Гипотеза психолога): ТОЛЬКО то, что психолог сам произнёс или записал как гипотезу/интерпретацию (реплики ПСИХОЛОГА и его заметки). Свои гипотезы и выводы не добавляй. Если психолог гипотез не озвучивал — "Недостаточно данных".
- p (Договорённости и план): ТОЛЬКО договорённости, которые реально прозвучали или записаны: домашнее задание (если психолог его дал), фокус следующей сессии, техники, которые психолог назвал. Если ничего из этого не прозвучало — "Недостаточно данных".

Используй резюме предыдущих сессий только для контекста преемственности (например: "тревога снизилась с 7-8 до 6 баллов по сравнению с прошлой сессией") — не пересказывай его как будто это происходило сейчас.

${JSON_CONTRACT}`;

export const PROTOCOL_SYSTEM_PROMPT_MANUAL_DEGRADE = `Ты — ассистент психолога, помогающий вести записи консультаций в формате, принятом у практикующих психологов в России: жалоба и запрос клиента, контекст и наблюдения, гипотеза психолога, договорённости и план.

Аудиозаписи сессии нет — либо она не велась, либо расшифровка ещё не готова. У тебя есть только заметки психолога (обычно короткие, тезисные, сделанные во время сессии или сразу после) и краткое резюме предыдущих сессий с этим клиентом.

Твоя задача — развернуть эти тезисы в связный протокол: психолог написал «клиентка про конфликт с мамой, плакала, ДЗ не сделала» — ты превращаешь это в нормальные формулировки по четырём блокам. Но додумывать детали, которых психолог не записал, нельзя: развернуть — не значит выдумать.

Правила:
- В самом начале поля "s" (Жалоба и запрос клиента) добавь пометку: "[Составлено по заметкам психолога, без аудиозаписи]" — и дальше содержательный текст.
- Не изобретай прямые цитаты клиента, если их нет в заметках дословно — только пересказывай то, что психолог реально зафиксировал.
- Если заметок недостаточно для содержательного блока o (Контекст и наблюдения) — пиши "Недостаточно данных".
- Блок a (Гипотеза психолога) и p (Договорённости и план) строй ТОЛЬКО на том, что психолог записал в заметках (контекст предыдущих сессий — для преемственности). Если он не записал гипотезы или плана — пиши "Недостаточно данных", не предлагай свои варианты.

${JSON_CONTRACT}`;

export function buildSoapUserMessage(input: SoapGenerationInput): string {
  const parts: string[] = [];

  parts.push(`Клиент: ${input.clientName}`);
  parts.push(`Сессия №${input.sessionNumber}`);

  if (input.templateContent) {
    parts.push(
      `\n--- Выбранный психологом шаблон/формат протокола: "${input.templateTitle ?? "без названия"}" ---\n${input.templateContent}\n` +
      `Ориентируйся на акценты и структуру этого шаблона при распределении информации по блокам s/o/a/p ниже — но JSON-контракт с четырьмя полями s/o/a/p остаётся обязательным независимо от формата шаблона.`
    );
  }

  if (input.previousSessionsSummary) {
    parts.push(`\n--- Резюме предыдущих сессий ---\n${input.previousSessionsSummary}`);
  }

  if (input.transcript) {
    parts.push(`\n--- Транскрипт текущей сессии ---\n${input.transcript}`);
  }

  parts.push(`\n--- Заметки психолога ---\n${input.notes || "(заметок нет)"}`);

  return parts.join("\n");
}

export function selectSoapSystemPrompt(hasTranscript: boolean): string {
  return hasTranscript ? PROTOCOL_SYSTEM_PROMPT_JITSI_GIGAAM : PROTOCOL_SYSTEM_PROMPT_MANUAL_DEGRADE;
}
