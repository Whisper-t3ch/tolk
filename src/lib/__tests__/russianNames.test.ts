import { describe, it, expect } from "vitest";
import { toNominativeWord, toNominativeName } from "../russianNames";

describe("toNominativeWord", () => {
  it("винительный → именительный", () => {
    const cases: Array<[string, string]> = [
      ["Алексея", "Алексей"], ["Марию", "Мария"], ["Олега", "Олег"], ["Светлану", "Светлана"], ["Анну", "Анна"],
      ["Дмитрия", "Дмитрий"], ["Юлию", "Юлия"], ["Наталью", "Наталья"], ["Илью", "Илья"], ["Никиту", "Никита"],
      ["Сашу", "Саша"], ["Женю", "Женя"], ["Игоря", "Игорь"], ["Артёма", "Артём"], ["Ивана", "Иван"],
      ["Екатерину", "Екатерина"], ["Андрея", "Андрей"], ["Сергея", "Сергей"], ["Татьяну", "Татьяна"], ["Ольгу", "Ольга"],
    ];
    for (const [from, to] of cases) expect(toNominativeWord(from)).toBe(to);
  });
  it("именительный не портится", () => {
    for (const n of ["Мария", "Никита", "Илья", "Саша", "Алексей", "Олег", "Анна", "Юлия", "Женя", "Лука", "Миша", "Катя"]) {
      expect(toNominativeWord(n)).toBe(n);
    }
  });
  it("неизвестное и не-слово не трогаем", () => {
    expect(toNominativeWord("Зульфия")).toBe("Зульфия");
    expect(toNominativeWord("Client1")).toBe("Client1");
  });
  it("полное имя: только первое слово", () => {
    expect(toNominativeName("Ивана Петрова")).toBe("Иван Петрова");
  });
});
