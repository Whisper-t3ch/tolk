export type Approach = "cbt" | "gestalt" | "psychoanalysis" | "schema" | "existential" | "integrative" | "other";

/**
 * Строит блок для системного промпта ассистента с учётом подхода,
 * специализации и типичного запроса психолога. Используется в
 * /api/assistant, чтобы модель адаптировала стиль ответов вместо
 * одного универсального тона для всех психологов.
 * Если профиль психолога ещё не заполнен (онбординг не пройден) —
 * возвращает пустую строку, вызывающий код просто её не добавляет.
 */
export function buildApproachContextBlock(profile: {
  approach: string | null;
  specialty: string | null;
  typical_client_request: string | null;
}): string {
  const approach = profile.approach as Approach | null;
  if (!approach || !(approach in APPROACH_LABELS)) return "";

  const styleHint = APPROACH_PROMPT_STYLE[approach];
  const label = APPROACH_LABELS[approach];

  return `Ты работаешь с психологом, который использует подход: ${label}.
Специализация: ${profile.specialty ?? "не указана"}.
Типичные клиенты: ${profile.typical_client_request || "не указано"}.

Адаптируй свои ответы под этот подход: отвечай ${styleHint}.`;
}

