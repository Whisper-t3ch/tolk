const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");
const MALE_SET = new Set(MALE.map(norm));
const FEMALE_SET = new Set(FEMALE.map(norm));
const isName = (s: string) => MALE_SET.has(norm(s)) || FEMALE_SET.has(norm(s));
const isMale = (s: string) => MALE_SET.has(norm(s));
const isFemale = (s: string) => FEMALE_SET.has(norm(s));

function matchCase(original: string, result: string): string {
  return original[0] === original[0].toUpperCase() ? result[0].toUpperCase() + result.slice(1) : result;
}

/** Одно слово-имя → именительный падеж; неизвестное или уже именительное возвращает без изменений. */
export function toNominativeWord(word: string): string {
  const w = word.trim();
  if (w.length < 3 || !/^[А-Яа-яЁё]+$/.test(w)) return w;
  if (isName(w)) return w; // уже именительный (Мария, Никита, Илья, Саша…)

  const cut = (n: number, add = "") => w.slice(0, w.length - n) + add;
  const lower = w.toLowerCase();

  // Окончания, невозможные в именительном падеже, правим безусловно.
  if (/ию$/.test(lower)) return cut(2, "ия"); // Марию → Мария
  if (/ью$/.test(lower)) return cut(2, "ья"); // Наталью → Наталья, Илью → Илья
  if (/[бвгджзклмнпрстфхцчшщ]у$/.test(lower)) return cut(1, "а"); // Анну → Анна, Светлану → Светлана, Никиту → Никита
  if (/[бвгджзклмнпрстфхцчшщ]ю$/.test(lower)) return cut(1, "я"); // Женю → Женя, Колю → Коля

  // Остальное — только если получилось известное имя.
  const tries: Array<[RegExp, string, (s: string) => boolean]> = [
    [/ея$/, "ей", isMale], // Алексея → Алексей
    [/ия$/, "ий", isMale], // Дмитрия → Дмитрий
    [/я$/, "ь", isMale], // Игоря → Игорь
    [/а$/, "", isMale], // Олега → Олег
    [/ы$/, "а", isFemale], // Анны → Анна
    [/ии$/, "ия", isFemale], // Марии → Мария
    [/и$/, "я", isFemale], // Ани → Аня
    [/и$/, "а", isFemale], // Ольги → Ольга
    [/у$/, "", isMale], // Олегу → Олег (дательный; на всякий случай)
  ];
  for (const [re, add, ok] of tries) {
    if (re.test(lower)) {
      const cand = w.replace(re, add);
      if (cand.length >= 2 && ok(cand)) return matchCase(w, cand);
    }
  }
  return w;
}

/** «Алексея» → «Алексей»; «Иван Петрова» → фамилию не трогаем (только первое слово). */
export function toNominativeName(full: string): string {
  const parts = full.trim().split(/\s+/);
  if (parts.length === 0) return full;
  parts[0] = toNominativeWord(parts[0]);
  return parts.join(" ");
}
