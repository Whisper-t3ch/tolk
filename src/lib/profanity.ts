// ============================================================
// Маскировка ненормативной лексики ДО отправки текста в YandexGPT.
//
// Зачем: модерация YandexGPT отклоняет запросы с матом (400 «Я не могу
// обсуждать эту тему»), и один резкий эпизод в реальной речи клиента
// ронял анонимизацию и генерацию протокола целиком. Мат в речи клиента
// сам по себе клинически не значим (значим факт эмоциональной
// остроты), поэтому заменяем слово нейтральным маркером и сохраняем
// остальной смысл. Маркер понятен модели и психологу.
//
// Подход — по целым словам (Unicode), а не по подстрокам: корни мата
// проверяются только в начале слова после допустимых приставок, чтобы
// не задевать обычные слова («хлеб», «себе», «требует», «употреблять»).
// Список намеренно ограничен «жёсткой» лексикой — расширяется в
// PROFANITY_PATTERNS ниже (по реальным случаям из тестов).
// ============================================================

export const PROFANITY_MARKER = "[нецензурное слово]";

// Приставки, с которыми корень остаётся матерным словом (заебал, нахер, выебывается).
const PREFIX = "(?:не|ни|на|по|за|о|об|от|вы|до|у|при|с|раз|рас|под|пере|про|вз|ис|из|недо|пре|съ|подъ|объ|все)*";

// Каждое выражение сверяется со ВСЕМ словом (нормализованным: нижний регистр, ё→е).
const PROFANITY_PATTERNS: RegExp[] = [
  // хуй и производные: хуй, хуе-, хуя-, хуи-, хую
  new RegExp(`^${PREFIX}ху[йеяию]\\p{L}*$`, "u"),
  // хер: исключаем «херувим» и подобные — только явные формы
  new RegExp(`^${PREFIX}(?:хер|хера|херу|хером|хере|херня|херни|херню|херней|херов\\p{L}*)$`, "u"),
  // пизд-
  new RegExp(`^${PREFIX}пизд\\p{L}*$`, "u"),
  // еб-: явные формы глагола, чтобы не задеть «себе», «ребёнок», «небо»
  new RegExp(`^${PREFIX}(?:еб(?:ал|ан|ат|аш|ну|уч|ыр|ор|ун|ис|ут|ет|еш|у)\\p{L}*|ебл\\p{L}*|еба\\p{L}*)$`, "u"),
  // бля-, блять
  new RegExp(`^(?:бля|блять|блядь|бляд\\p{L}*|блят\\p{L}*)$`, "u"),
  // сука и производные (только формы слова, не «сукно»)
  new RegExp(`^(?:сука|суки|суке|суку|сукой|сучка|сучки|сучку|сучк\\p{L}*|сучар\\p{L}*)$`, "u"),
  // мудак, мудила
  new RegExp(`^${PREFIX}муд(?:ак|ил|ач|о[хв])\\p{L}*$`, "u"),
  // пидор/пидар
  new RegExp(`^${PREFIX}пид[оа]р\\p{L}*$`, "u"),
  // говно
  new RegExp(`^${PREFIX}говн\\p{L}*$`, "u"),
  // залупа, гандон, шлюха, дрочить
  new RegExp(`^${PREFIX}(?:залуп|гандон|шлюх|дроч)\\p{L}*$`, "u"),
];

function normalizeWord(word: string): string {
  return word.toLowerCase().replace(/ё/g, "е");
}

export function isProfaneWord(word: string): boolean {
  const normalized = normalizeWord(word);
  return PROFANITY_PATTERNS.some(pattern => pattern.test(normalized));
}

/** Заменяет ненормативные слова маркером. Остальной текст не меняется (пробелы, пунктуация, регистр остальных слов). */
export function maskProfanity(text: string): string {
  if (!text) return text ?? "";
  return text.replace(/\p{L}+/gu, word => (isProfaneWord(word) ? PROFANITY_MARKER : word));
}

export function containsProfanity(text: string): boolean {
  if (!text) return false;
  const words = text.match(/\p{L}+/gu) ?? [];
  return words.some(isProfaneWord);
}
