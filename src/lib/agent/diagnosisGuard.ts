// Модель не должна ставить диагнозы (правило в системном промпте). GigaChat правило соблюдает, пока
// отвечает «из общих соображений», но, прочитав историю клиента, уверенно пишет «можно предположить
// наличие ГТР». Ловим такие формулировки в готовом ответе и просим переписать.
const DISORDER = "(?:расстройств\\S*|ГТР|депресси\\S*|ПТСР|ОКР|СДВГ|биполяр\\S*|шизофрени\\S*|дистими\\S*|паническ\\S* расстройств\\S*)";
const DIAGNOSIS_RE = new RegExp(
  [
    `(?:предположить|предполагать|предполагаю|заподозрить|подозревать)\\s+(?:наличие\\s+)?[^.!?\\n]{0,40}${DISORDER}`,
    `наличи\\S*\\s+[^.!?\\n]{0,30}${DISORDER}`,
    `(?:соответств\\S*|указыва\\S* на|похож\\S* на|характерн\\S* для|укладыва\\S* в)\\s+[^.!?\\n]{0,40}${DISORDER}`,
    `(?:^|[.!?]\\s*)(?:да,?\\s*)?это\\s+(?:похоже\\s+на\\s+)?${DISORDER}`,
  ].join("|"),
  "i"
);

export function looksLikeDiagnosis(text: string): boolean {
  return DIAGNOSIS_RE.test(text);
}

