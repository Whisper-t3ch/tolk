// Чат ассистента показывает только простой текст. Промпт запрещает markdown, но GigaChat его
// всё равно использует (заголовки ##, **жирный**, списки), и решётки со звёздочками видны буквально.
// Поэтому сервер приводит ответ к простому тексту перед показом психологу.
export function plainifyMarkdown(text: string): string {
  return text
    .split("\n")
    .map(line => {
      let l = line;
      if (/^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(l)) return "";
      l = l.replace(/^\s*#{1,6}\s+/, "");
      l = l.replace(/^(\s*)[-*•+]\s+/, "$1— ");
      l = l.replace(/\*\*(.+?)\*\*/g, "$1").replace(/__(.+?)__/g, "$1");
      l = l.replace(/(^|[\s(])\*(\S[^*]*?)\*(?=[\s.,!?:;)]|$)/g, "$1$2");
      l = l.replace(/`([^`]+)`/g, "$1");
      return l;
    })
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
