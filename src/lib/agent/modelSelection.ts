import type { YandexGptModel } from "@/lib/yandexgpt";

// ------------------------------------------------------------
// Выбор модели ассистента ДО начала агентского цикла — эвристика
// по тексту сообщения психолога, без дополнительного сетевого
// вызова. Модель выбирается ОДИН РАЗ и используется на всех
// итерациях цикла (в т.ч. при tool calls) — то есть в рамках одной
// serverless-функции всегда ровно один "путь" по стоимости, никогда
// не бывает вызова lite и following-up вызова pro в одном запросе.
//
// Это принципиально отличается от откаченного ранее каскада
// lite→pro (см. комментарий в /api/assistant, POST): там модель
// выбиралась ПОСЛЕ первого ответа (по факту, ответил ли lite текстом
// или запросил tool call), что означало до двух последовательных
// сетевых вызовов к YandexGPT в одной serverless-функции и превышало
// таймаут Vercel. Здесь решение принимается заранее и дешёво (без
// сети), поэтому по стоимости за запрос гарантированно один вызов,
// как и было при полном откате на pro — просто не всегда именно pro.
//
// Эвристика консервативна: при малейшей неопределённости выбираем
// pro. Задача — снять только явно дешёвые случаи (короткие бытовые
// вопросы по платформе, не требующие анализа данных клиента), а не
// экономить агрессивно ценой качества ответов на аналитику.
// ------------------------------------------------------------

// Слова, сигнализирующие "нужен вдумчивый анализ" — период, тенденции,
// динамика, отчёты, интерпретация данных клиента. При наличии любого
// такого слова — всегда pro, независимо от длины сообщения.
const DEEP_ANALYSIS_KEYWORDS = [
  "тенденци", "динамик", "анализ", "проанализир", "паттерн",
  "прогресс", "период", "итог", "сводк", "резюме", "статистик",
  "сравни", "сравнени", "изменил", "закономерност", "интерпрет",
];

// Признаки простого справочно-навигационного вопроса про саму
// платформу/интерфейс, а не про клиентов и терапию — здесь достаточно
// lite.
const PLATFORM_HELP_KEYWORDS = [
  "как пользоваться", "как работает", "как настроить", "где найти",
  "где посмотреть", "как включить", "как выключить", "не работает",
  "не открывается", "как добавить", "как удалить",
];

const SHORT_MESSAGE_THRESHOLD = 60;

export function selectAssistantModel(userMessage: string, hasHistory: boolean): YandexGptModel {
  const text = userMessage.toLowerCase();

  const looksLikeDeepAnalysis = DEEP_ANALYSIS_KEYWORDS.some(kw => text.includes(kw));
  if (looksLikeDeepAnalysis) return "pro";

  const looksLikePlatformHelp = PLATFORM_HELP_KEYWORDS.some(kw => text.includes(kw));
  // Короткий вопрос про платформу без истории диалога — типичный
  // "быстрый" сценарий ориентации на платформе из примера пользователя.
  // Если уже есть история (продолжение диалога) — надёжнее pro: модель
  // должна корректно опираться на контекст предыдущих реплик.
  if (looksLikePlatformHelp && !hasHistory && userMessage.length <= SHORT_MESSAGE_THRESHOLD) {
    return "lite";
  }

  return "pro";
}
