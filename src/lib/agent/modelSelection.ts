import type { YandexGptModel } from "@/lib/yandexgpt";

// ------------------------------------------------------------
// Выбор модели ассистента ДО начала агентского цикла — эвристика
// по тексту сообщения психолога, без дополнительного сетевого
// вызова. Модель выбирается ОДИН РАЗ и используется на всех
// итерациях цикла (в т.ч. при tool calls) — то есть в рамках одной
// serverless-функции всегда ровно один "путь" по стоимости, никогда
// не бывает вызова lite и following-up вызова pro в одном запросе.
//
// Это принципиально отличается от откаченного ранее каскада
// lite→pro (см. комментарий в /api/assistant, POST): там модель
// выбиралась ПОСЛЕ первого ответа (по факту, ответил ли lite текстом
// или запросил tool call), что означало до двух последовательных
// сетевых вызовов к YandexGPT в одной serverless-функции и превышало
// таймаут Vercel. Здесь решение принимается заранее и дешёво (без
// сети), поэтому по стоимости за запрос гарантированно один вызов,
// как и было при полном откате на pro — просто не всегда именно pro.
//
// Эвристика консервативна: при малейшей неопределённости выбираем
// pro. Задача — снять явно дешёвые случаи (вопросы про саму
// платформу, не требующие данных клиента), а не экономить агрессивно
// ценой качества ответов на аналитику.
//
// ПЕРЕСМОТР после разбора биллинга: прошлая версия отправляла в lite
// лишь около четверти даже справочных вопросов, и мешали ей три вещи,
// каждая из которых била мимо цели.
//   1. Требовалось ТОЧНОЕ вхождение фразы из короткого списка, поэтому
//      «как поменять часовой пояс», «как выгрузить протокол в PDF»,
//      «почему клиенту не пришло сообщение» уходили в pro — при том,
//      что это очевидные вопросы про интерфейс.
//   2. Любая история диалога принудительно давала pro. Но дорогой
//      запрос делает не факт истории, а содержание ВОПРОСА: «как
//      поменять часовой пояс» стоит одинаково дёшево и первым
//      сообщением, и десятым.
//   3. Порог в 60 знаков резал нормальные человеческие формулировки:
//      «Как мне поменять часовой пояс, чтобы напоминания клиентам
//      приходили вовремя?» — 70 знаков и ничуть не сложнее.
// ------------------------------------------------------------

// Слова, сигнализирующие "нужен вдумчивый анализ" — динамика,
// интерпретация, закономерности в данных клиента. При наличии любого
// такого слова — всегда pro, независимо от длины сообщения.
//
// «период» и «итог» намеренно убраны из безусловных триггеров: сами по
// себе они ничего не решают. «Срез за период по Марине» — это анализ,
// а «что такое срез за период» — вопрос про интерфейс, и по одному
// слову их не различить. Оба слова теперь учитываются только вместе с
// признаком работы с данными клиента (см. CLIENT_DATA_MARKERS ниже).
const DEEP_ANALYSIS_KEYWORDS = [
  "тенденци", "динамик", "проанализир", "паттерн",
  "прогресс", "сводк", "резюме", "статистик",
  "сравни", "сравнени", "изменил", "закономерност", "интерпрет",
];

// Слова, которые означают анализ ТОЛЬКО в связке с данными клиента.
const AMBIGUOUS_ANALYSIS_KEYWORDS = ["период", "итог", "анализ", "срез"];

// Признаки того, что речь о КОНКРЕТНОМ клиенте и его данных, а не об
// устройстве платформы. Само слово «клиент» таким признаком быть не
// может: «что видит клиент при переходе по ссылке» и «чтобы
// напоминания клиентам приходили вовремя» — вопросы про интерфейс, в
// них клиент упомянут обобщённо. Поэтому ловим либо клиента с
// определением («у клиента», «карточка клиента», «моего клиента»),
// либо предметные сущности его дела — сессии, тесты, ДЗ, протоколы.
// \b перед предлогом обязателен: без него «по клиент» находится внутри
// «почему клиенту не пришло сообщение» (…«по»+«чему клиенту»…), и
// вопрос про недоставку уезжает в pro.
const CLIENT_DATA_MARKERS = [
  "\\bу клиент", "\\bпо клиент", "\\bэтого клиент", "\\bмоего клиент", "\\bмоих клиент",
  "карточк[аеиу] клиент", "данн\\w* клиент", "истори\\w* клиент",
  "пациент",
  "\\bу мари", "\\bу ольг", "\\bу дмитри", "\\bпо мари", "\\bпо ольг",
  "сесси", "тест", "домашн", "\\bдз\\b", "протокол по",
  "его состоян", "её состоян", "ее состоян",
];

// Обобщённое упоминание клиента («клиенту не пришло», «что видит
// клиент») — не признак работы с данными: такие вопросы про доставку и
// интерфейс и спокойно уходят в lite.

// Явные начала справочно-навигационных вопросов про саму платформу.
// Проверяются как ПРЕФИКСЫ (вопрос с них начинается) — это надёжнее
// поиска подстроки где угодно: «как удалить» в начале почти всегда про
// интерфейс, а в середине фразы «расскажи, как удалить тревогу у
// клиента» — уже нет.
const PLATFORM_HELP_PREFIXES = [
  "как поменять", "как сменить", "как изменить", "как настроить",
  "как выгрузить", "как скачать", "как экспортировать", "как включить",
  "как выключить", "как отключить", "как подключить", "как добавить",
  "как удалить", "как создать", "как отправить", "как найти",
  "как пользоваться", "как работает", "как посмотреть", "как открыть",
  "где найти", "где посмотреть", "где нахо", "где в ",
  "почему не пришло", "почему не приходит", "почему не работает",
  "почему не отправ", "почему клиенту не", "что такое", "что означает",
  "можно ли", "нужно ли", "зачем нужен", "зачем нужна", "зачем нужно",
];

// Те же темы, но упомянутые не в начале фразы — сигнал слабее,
// поэтому засчитывается только вместе с отсутствием клиентских
// маркеров и отсутствием слов глубокого анализа.
const PLATFORM_HELP_KEYWORDS = [
  "не работает", "не открывается", "не отправляется", "не приходит",
  "часовой пояс", "интерфейс", "настройк", "шаблон протокол",
  "публичная запись", "ссылк на запись", "тариф", "лимит запрос",
];

// Мягкий потолок вместо прежних 60 знаков: длина — плохой показатель
// сложности, но совсем без ограничения в lite может уехать развёрнутое
// рассуждение психолога, которое лучше отдать pro.
const LONG_MESSAGE_THRESHOLD = 180;

function hasAny(text: string, list: string[]): boolean {
  return list.some(kw => new RegExp(kw).test(text));
}

export function selectAssistantModel(userMessage: string, hasHistory: boolean): YandexGptModel {
  // hasHistory больше не влияет на выбор: стоимость запроса определяет
  // содержание вопроса, а не наличие предыдущих реплик. Параметр
  // оставлен в сигнатуре, чтобы не править вызывающий код и чтобы
  // намерение было видно в диффе.
  void hasHistory;

  const text = userMessage.toLowerCase().trim();

  const mentionsClientData = hasAny(text, CLIENT_DATA_MARKERS);

  // Безусловная аналитика — всегда pro.
  if (hasAny(text, DEEP_ANALYSIS_KEYWORDS)) return "pro";

  // Неоднозначные слова ("период", "итог", "анализ", "срез") считаются
  // аналитикой только если рядом есть признак данных клиента.
  if (hasAny(text, AMBIGUOUS_ANALYSIS_KEYWORDS) && mentionsClientData) return "pro";

  // Вопрос явно про клиента — pro, даже если начинается как справочный
  // ("как посмотреть тесты Марины" — нужен доступ к данным).
  if (mentionsClientData) return "pro";

  if (text.length > LONG_MESSAGE_THRESHOLD) return "pro";

  const startsAsHelp = PLATFORM_HELP_PREFIXES.some(p => text.startsWith(p));
  if (startsAsHelp) return "lite";

  if (hasAny(text, PLATFORM_HELP_KEYWORDS)) return "lite";

  return "pro";
}
