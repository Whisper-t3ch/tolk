// списка оптимизаций стоимости, 20-21.09) — третья попытка сузить
// набор из 18 инструментов, передаваемых в каждом LLM-вызове
// agent loop. Полная схема AGENT_TOOLS в JSON — тысячи символов,
// передаётся на КАЖДОЙ итерации (обычно 2-3 на запрос), независимо
// от того, что реально нужно для конкретного вопроса психолога —
// это и есть главная находка этой сессии тестирования: фиксированные
// накладные расходы (промпт + схема инструментов) доминируют над
// стоимостью RAG-контекста, у клиента с 1 сессией и у клиента с 10
// сессиями цена запроса примерно одинаковая.
//
// ДВА ПРЕДЫДУЩИХ ПРОВАЛА того же намерения (сузить набор инструментов):
// 1) topK 5→3 в search_client_history — не про выбор ИНСТРУМЕНТА, но
//    тот же принцип "сузить, чтобы сэкономить" — провалился на
//    worst-case (сравнение первой/последней сессии).
// 2) Domain routing по жёстким keyword-правилам — провалился, потому
//    что реальный вопрос психолога использует синонимы, которых нет
//    в списке ключевых слов (например "злость" не входило в список,
//    хотя семантически явно про search_client_history).
//
// ПОЧЕМУ ЭТОТ ПОДХОД ДРУГОЙ: вместо жёстких правил — семантическая
// близость через ту же embedding-модель, что уже используется для
// RAG по транскриптам (text-search-doc/text-search-query, 256
// измерений). "Злость" и "гнев" оказываются близки в векторном
// пространстве даже без точного совпадения ключевых слов — именно
// то, чего не хватало keyword-routing.
//
// ЗАЩИТА ОТ ТРЕТЬЕГО ПРОВАЛА:
// - top-6-8 инструментов, не top-3-5 — заметно шире принятого в
//   первой попытке domain routing (там резали до 1 группы инструментов).
// - find_client_by_name добавляется ВСЕГДА — он нужен почти в любом
//   сценарии с конкретным клиентом, и его отсутствие в узком наборе
//   было бы фатальным, а не косметическим недочётом.
// - Обязательный fallback на ПОЛНЫЙ набор из 18 инструментов, если
//   уверенность (score top-1) ниже порога — лучше отказаться от
//   экономии на неоднозначном вопросе, чем рисковать тем что нужный
//   инструмент не попал в узкий список и модель не справится.
// - Согласно протоколу тестирования: если ХОТЯ БЫ ОДИН живой тест
//   покажет что нужный инструмент не попал в список — весь механизм
//   откатывается полностью, не патчится точечно.
// ============================================================
