interface ToolEmbedding {
  name: AgentToolName;
  vector: number[];
}

// In-memory кэш эмбеддингов инструментов на уровне модуля — считается
// один раз за время жизни serverless-инстанса (Vercel переиспользует
// тёплые инстансы между запросами), а не на каждый вопрос психолога.
// Без этого кэша механизм добавлял бы лишний сетевой вызов к
// YandexGPT Embeddings на КАЖДЫЙ запрос — это свело бы на нет
// экономию, ради которой всё затевалось.
let toolEmbeddingsCache: ToolEmbedding[] | null = null;
let toolEmbeddingsPromise: Promise<ToolEmbedding[]> | null = null;

function cosineSimilarity(a: number[], b: number[]): number {
  let dot = 0;
  let normA = 0;
  let normB = 0;
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }
  if (normA === 0 || normB === 0) return 0;
  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}

async function computeToolEmbeddings(): Promise<ToolEmbedding[]> {
  const entries = Object.entries(TOOL_EXAMPLES) as [AgentToolName, string[]][];
  const results: ToolEmbedding[] = [];
  for (const [name, examples] of entries) {
    // Один эмбеддинг на инструмент — усредняем по всем примерам, а не
    // делаем отдельный вектор на каждый пример: иначе пришлось бы
    // хранить и сравнивать много векторов на инструмент, а усреднение
    // достаточно для устойчивого отделения тематически разных
    // инструментов друг от друга.
    const combinedText = examples.join(". ");
    const vector = await yandexGptEmbed(combinedText, "doc");
    results.push({ name, vector });
  }
  return results;
}

async function getToolEmbeddings(): Promise<ToolEmbedding[]> {
  if (toolEmbeddingsCache) return toolEmbeddingsCache;
  if (!toolEmbeddingsPromise) {
    toolEmbeddingsPromise = computeToolEmbeddings()
      .then(result => {
        toolEmbeddingsCache = result;
        return result;
      })
      .catch(e => {
        // Сбой вычисления эмбеддингов инструментов не должен ронять
        // основной запрос — вызывающий код (selectRelevantTools)
        // трактует исключение как сигнал вернуть полный набор
        // инструментов, как будто механизма выбора не было вовсе.
        toolEmbeddingsPromise = null;
        throw e;
      });
  }
  return toolEmbeddingsPromise;
}

export interface ToolSelectionResult {
  tools: YandexGptTool[];
  // Для телеметрии/отладки — не влияет на поведение, но полезно при
  // мониторинге, действительно ли механизм сужает набор на практике.
  narrowed: boolean;
  selectedNames: AgentToolName[];
}

/**
 * Возвращает подмножество AGENT_TOOLS, семантически релевантное
 * вопросу психолога. При любой неопределённости (ошибка эмбеддинга,
 * низкая уверенность top-1) возвращает ПОЛНЫЙ набор — узкий список
 * должен строго ДОКАЗАТЬ свою уверенность, а не наоборот.
 */
export async function selectRelevantTools(userMessage: string): Promise<ToolSelectionResult> {
  const fullResult: ToolSelectionResult = {
    tools: AGENT_TOOLS,
    narrowed: false,
    selectedNames: AGENT_TOOLS.map(t => t.function.name as AgentToolName),
  };

  let toolEmbeddings: ToolEmbedding[];
  let queryVector: number[];
  try {
    [toolEmbeddings, queryVector] = await Promise.all([
      getToolEmbeddings(),
      yandexGptEmbed(userMessage, "query"),
    ]);
  } catch (e) {
    console.error("toolSelection: не удалось получить эмбеддинги, используем полный набор", e instanceof Error ? e.message : String(e));
    return fullResult;
  }

  const scored = toolEmbeddings
    .map(te => ({ name: te.name, score: cosineSimilarity(queryVector, te.vector) }))
    .sort((a, b) => b.score - a.score);

  if (scored.length === 0 || scored[0].score < CONFIDENCE_THRESHOLD) {
    return fullResult;
  }

  const selectedNames = new Set<AgentToolName>([ALWAYS_INCLUDED]);
  for (const s of scored.slice(0, TOP_K_TOOLS)) {
    selectedNames.add(s.name);
  }

  const narrowedTools = AGENT_TOOLS.filter(t => selectedNames.has(t.function.name as AgentToolName));

  return {
    tools: narrowedTools,
    narrowed: true,
    selectedNames: Array.from(selectedNames),
  };
}
