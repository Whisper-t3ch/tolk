// ============================================================
// Общие типы браузерной записи консультации.
//
// Архитектурное решение (2026-09-22, заменяет Jibri): запись выполняется
// ТОЛЬКО в браузере психолога и содержит обе стороны разговора двумя
// раздельными дорожками — локальный микрофон психолога и удалённая
// аудиодорожка клиента, полученная из WebRTC-соединения. На устройстве
// клиента не создаётся MediaRecorder, не используется IndexedDB под
// аудио и ничего не выгружается в хранилище.
//
// Почему две дорожки, а не один смешанный файл: точное определение
// спикера без диаризации, независимая нормализация громкости, удаление
// тишины перед ASR, обнаружение пропадания одной из сторон и
// возможность переобработать только проблемного спикера.
//
// Модуль сознательно НЕ зависит от Jitsi: на вход подаются готовые
// MediaStream. Это позволяет (1) тестировать рекордер на синтетических
// потоках без видеосервера и (2) пережить смену способа интеграции
// звонка, не переписывая запись.
// ============================================================

/** Кто говорит на дорожке. Значения попадают в ключи объектов в хранилище. */
export type TrackRole = "psychologist" | "client";

export const TRACK_ROLES: readonly TrackRole[] = ["psychologist", "client"] as const;

/**
 * Один фрагмент записи, полученный из MediaRecorder.
 *
 * ВАЖНО: фрагмент НЕ является самостоятельным аудиофайлом. При записи
 * в WebM/Opus заголовок контейнера попадает только в первый фрагмент,
 * остальные — продолжение потока. Поэтому backend обязан хранить
 * последовательность и собирать/ремуксить дорожку целиком (FFmpeg)
 * перед отправкой в ASR, а не расшифровывать фрагменты поодиночке.
 */
export interface RecordedChunk {
  role: TrackRole;
  /** Сквозной номер внутри дорожки, начиная с 0. Дыр быть не должно. */
  sequence: number;
  blob: Blob;
  /** Смещение начала фрагмента от старта записи дорожки, мс. */
  startedAtMs: number;
  /** Фактическая длительность фрагмента, мс (не равна timeslice в точности). */
  durationMs: number;
  mimeType: string;
  size: number;
  /** "sha256:<hex>" — считается в браузере, backend сверяет при приёме. */
  checksum: string;
}

/** Состояние записи одной дорожки — то, что показывается психологу и уходит в heartbeat. */
export type TrackState =
  | "idle"
  | "recording"
  /** Дорожка исчезла (клиент отключился / выключил микрофон на уровне устройства). */
  | "track_lost"
  | "stopped"
  | "failed";

export interface TrackStatus {
  role: TrackRole;
  state: TrackState;
  /** Номер последнего нарезанного фрагмента, -1 если ещё ничего не было. */
  lastChunkSequence: number;
  mimeType: string | null;
  error: string | null;
}

/**
 * Диагностика остановки MediaRecorder (25.09.2026, вместе с
 * исправлением TrackRecorder.stop()) — НЕ источник истины для
 * целостности записи (это manifest + реестр фрагментов), а
 * телеметрия для разбора конкретно вопроса "почему запись
 * продолжилась дольше, чем решил браузер". Класс сам НЕ знает про
 * attemptId (архитектурно ничего не знает про выгрузку/Jitsi, см.
 * заголовок файла) — attemptId подставляется тем, кто собирает эти
 * события (JitsiCallView), аналогично тому, как ChunkUploader
 * подставляет attemptId в manifest, а не SessionRecorder.
 *
 * НИКОГДА не должно содержать: байты/контент фрагмента, checksum как
 * идентификатор содержимого, подписанные токены/URL хранилища — по
 * требованию пользователя диагностика не должна протекать аудио или
 * секреты через этот канал (он уходит в recording_client_state,
 * который в целом не секретный, но лишний риск ни к чему).
 */
export interface StopDiagnosticEvent {
  role: TrackRole;
  /** performance.now() в момент события — относительное время, не unix ts. */
  ts: number;
  event:
    | "stop_requested"
    | "dataavailable_during_stop"
    | "onstop"
    | "stop_threw"
    | "stop_timeout"
    | "stop_result";
  /** MediaRecorder.state на момент события, если применимо. */
  state?: string;
  /** Размер blob'а (байты) — только число, не содержимое. */
  size?: number;
  /** Сообщение ошибки (наше собственное, не содержимое фрагмента). */
  error?: string;
  /** Итог stop_result: реально ли подтверждена остановка (см. TrackRecorder.stop()). */
  confirmed?: boolean;
}

/**
 * Manifest завершённой записи. Отправляется на backend после остановки —
 * именно по нему проверяется целостность (все ли номера на месте, нет ли
 * дублей, насколько разъехались длительности дорожек) прежде чем сессия
 * получит статус готовности к расшифровке.
 */
export interface RecordingManifest {
  sessionId: string;
  startedAt: string;
  finishedAt: string;
  /**
   * recording_attempt_id этой попытки записи (см. .../recording/
   * attempts/route.ts и migration_038_recording_attempt_id.sql).
   * Подставляется в ChunkUploader.sendManifest() из его собственного
   * закэшированного attemptId, не отсюда — SessionRecorder ничего не
   * знает про attempt_id, это забота uploader'а. null — только если
   * ни один фрагмент так и не пытались выгрузить за всю попытку
   * (например, консультация завершилась мгновенно после preflight);
   * backend в этом случае не сможет отфильтровать проверку по
   * попытке и сверяет по сессии в целом (см. комментарий в
   * .../recording/manifest/route.ts).
   */
  attemptId?: string | null;
  tracks: Array<{
    role: TrackRole;
    mimeType: string | null;
    firstSequence: number;
    lastSequence: number;
    /** Сколько фрагментов реально нарезано — для сверки с диапазоном номеров. */
    chunkCount: number;
    totalDurationMs: number;
    state: TrackState;
  }>;
}
